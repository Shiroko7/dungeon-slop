// Agent skills live once in `.agents/skills/<name>/SKILL.md`, the folder Codex,
// Gemini CLI and Cursor read. Claude Code reads only `.claude/skills/`, so this
// script writes a small pointer there for each shared skill.
//
//   bun run skills:sync          write or refresh the pointers
//   bun run skills:sync --check  fail if any pointer is missing or stale

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

export const SHARED_DIR = ".agents/skills";
export const CLAUDE_DIR = ".claude/skills";
export const POINTER_MARKER = "<!-- generated by scripts/sync-skills.ts from .agents/skills -->";

export type SharedSkill = { dir: string; name: string; description: string; frontmatter: string };

const NAME_RULE = /^[a-z0-9]+(-[a-z0-9]+)*$/;

export function parseSkill(dir: string, text: string): SharedSkill {
  const match = text.replace(/^﻿/, "").match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/);
  if (!match) throw new Error(`${dir}/SKILL.md must start with YAML frontmatter between --- lines`);
  const frontmatter = (match[1] ?? "").replace(/\r\n/g, "\n");
  const field = (key: string) => frontmatter.match(new RegExp(`^${key}:[ \\t]*(.+)$`, "m"))?.[1]?.trim() ?? "";
  const name = field("name");
  const description = field("description");
  if (name !== dir) throw new Error(`${dir}/SKILL.md: name "${name}" must match its folder name`);
  if (name.length > 64 || !NAME_RULE.test(name)) {
    throw new Error(`${dir}/SKILL.md: name must be 1-64 lowercase letters, digits and single hyphens`);
  }
  if (!description) throw new Error(`${dir}/SKILL.md: description is required`);
  if (description.length > 1024) throw new Error(`${dir}/SKILL.md: description is over 1024 characters`);
  return { dir, name, description, frontmatter };
}

export function readSharedSkills(root: string): SharedSkill[] {
  const base = join(root, SHARED_DIR);
  if (!existsSync(base)) return [];
  return readdirSync(base, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && existsSync(join(base, entry.name, "SKILL.md")))
    .map((entry) => parseSkill(entry.name, readFileSync(join(base, entry.name, "SKILL.md"), "utf8")))
    .sort((a, b) => a.name.localeCompare(b.name));
}

export function pointerFor(skill: SharedSkill): string {
  return [
    "---",
    skill.frontmatter,
    "---",
    "",
    POINTER_MARKER,
    "",
    `This skill is shared with other agents. Read \`${SHARED_DIR}/${skill.dir}/SKILL.md\` at the repository root now and follow it. Links inside it are relative to that folder.`,
    "",
  ].join("\n");
}

type Plan = { write: Map<string, string>; remove: string[] };

export function planSync(root: string): Plan {
  const write = new Map<string, string>();
  const shared = readSharedSkills(root);
  for (const skill of shared) write.set(join(root, CLAUDE_DIR, skill.dir, "SKILL.md"), pointerFor(skill));

  // A pointer whose shared skill was deleted or renamed is stale. Skills written
  // only for Claude (no marker) are left alone.
  const remove: string[] = [];
  const claudeBase = join(root, CLAUDE_DIR);
  if (existsSync(claudeBase)) {
    const names = new Set(shared.map((s) => s.dir));
    for (const entry of readdirSync(claudeBase, { withFileTypes: true })) {
      const file = join(claudeBase, entry.name, "SKILL.md");
      if (!entry.isDirectory() || names.has(entry.name) || !existsSync(file)) continue;
      if (readFileSync(file, "utf8").includes(POINTER_MARKER)) remove.push(join(claudeBase, entry.name));
    }
  }
  return { write, remove };
}

export function staleFiles(root: string): string[] {
  const { write, remove } = planSync(root);
  // Compare without line endings: a checkout with core.autocrlf rewrites them.
  const same = (file: string, text: string) => readFileSync(file, "utf8").replace(/\r\n/g, "\n") === text;
  const stale = [...write].filter(([file, text]) => !existsSync(file) || !same(file, text));
  return [...stale.map(([file]) => file), ...remove];
}

if (import.meta.main) {
  const root = resolve(import.meta.dir, "..");
  if (process.argv.includes("--check")) {
    const stale = staleFiles(root);
    if (stale.length) {
      console.error(`Claude skill pointers are out of date. Run \`bun run skills:sync\`.\n${stale.join("\n")}`);
      process.exit(1);
    }
    console.log("Claude skill pointers are up to date.");
  } else {
    const { write, remove } = planSync(root);
    for (const [file, text] of write) {
      mkdirSync(resolve(file, ".."), { recursive: true });
      writeFileSync(file, text);
    }
    for (const dir of remove) rmSync(dir, { recursive: true });
    console.log(`Wrote ${write.size} pointer(s), removed ${remove.length}.`);
  }
}
